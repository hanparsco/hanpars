"""Subset Alibaba PuHuiTi into frequency-ordered unicode-range slices for the Chinese pages."""
import json, os
from fontTools import subset
from fontTools.ttLib import TTFont
S = '/tmp/claude-0/-home-claude/c84510ce-5212-5f05-99da-4b6835ce3d16/scratchpad'
OUT = S + '/hanpars/public/fonts/puhuiti'
os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT): os.remove(os.path.join(OUT, f))

used = [ch for ch, _ in json.load(open(S + '/zh-chars.json'))]
# GB2312 level-1 (3,755 most common characters) as future-proof reserve
level1 = []
for hi in range(0xB0, 0xD8):
    for lo in range(0xA1, 0xFF):
        try: level1.append(bytes([hi, lo]).decode('gb2312'))
        except UnicodeDecodeError: pass
base = [chr(c) for c in range(0x20, 0x7F)] + [chr(c) for c in range(0xA0, 0x180)] + list('–—‘’“”…·•→←✓°±×µ®™€～（）：；，。、？！《》ﬂ')
order, seen = [], set()
for ch in base + used + level1:
    if ch not in seen: seen.add(ch); order.append(ch)
cmap = TTFont(S + '/puhui-zip/Alibaba-PuHuiTi-Regular.ttf').getBestCmap()
order = [ch for ch in order if ord(ch) in cmap]
# slice 0: Latin + punctuation + 500 most frequent Han; then 450-character slices
first = len([c for c in base if ord(c) in cmap]) + 500
slices = [order[:first]] + [order[i:i + 450] for i in range(first, len(order), 450)]

def ranges(chars):
    cps = sorted(ord(c) for c in chars); out = []; start = prev = cps[0]
    for c in cps[1:]:
        if c == prev + 1: prev = c; continue
        out.append((start, prev)); start = prev = c
    out.append((start, prev))
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in out)

css = ['/* Alibaba PuHuiTi (阿里巴巴普惠体), subset and sliced for the Chinese pages. Generated by make-puhuiti.py */']
total = 0
for weight, fname in ((400, 'Regular'), (500, 'Medium'), (700, 'Bold')):
    src = f'{S}/puhui-zip/Alibaba-PuHuiTi-{fname}.ttf'
    for i, chars in enumerate(slices):
        opts = subset.Options(); opts.flavor = 'woff'; opts.layout_features = ['*']; opts.name_IDs = ['*']; opts.notdef_outline = True; opts.hinting = False
        font = subset.load_font(src, opts)
        sub = subset.Subsetter(opts); sub.populate(unicodes=[ord(c) for c in chars]); sub.subset(font)
        path = f'{OUT}/{fname.lower()}-{i:02d}.woff'
        subset.save_font(font, path, opts); total += os.path.getsize(path)
        css.append(f"@font-face {{ font-family:'PuHuiTi'; font-style:normal; font-weight:{weight}; font-display:swap; src:url('/fonts/puhuiti/{fname.lower()}-{i:02d}.woff') format('woff'); unicode-range:{ranges(chars)}; }}")
open(f'{OUT}/puhuiti.css', 'w').write('\n'.join(css) + '\n')
sizes = sorted(os.path.getsize(f'{OUT}/{f}') for f in os.listdir(OUT) if f.startswith('regular'))
print('slices', len(slices), 'chars', len(order), 'total MB', round(total / 1e6, 1), 'regular slice KB min/max', sizes[0] // 1024, sizes[-1] // 1024, 'css KB', os.path.getsize(f'{OUT}/puhuiti.css') // 1024)
